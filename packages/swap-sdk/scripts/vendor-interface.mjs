// Copies the SDK into the Uniswap interface fork (no cross-repo import) and writes the fork's deployment file.
//   node packages/swap-sdk/scripts/vendor-interface.mjs [--deployment deployments/unichain-sepolia.json]
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, posix, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repo = resolve(pkg, '../..')
const target = join(repo, 'interface/packages/uniswap/src/features/predictionMarkets')
const flag = process.argv.indexOf('--deployment')
const deploymentPath =
  flag > 0 && process.argv[flag + 1] ? resolve(process.argv[flag + 1]) : join(repo, 'deployments/unichain-sepolia.json')

if (!existsSync(target)) throw new Error(`missing ${target}; clone the interface fork first`)

const HEADER =
  '// Vendored from packages/swap-sdk by packages/swap-sdk/scripts/vendor-interface.mjs. Do not edit here.\n'
const MODULE = 'uniswap/src/features/predictionMarkets/sdk'
const rewrite = (src, dir) =>
  src.replace(/from '(\.{1,2}\/[^']+)\.ts'/g, (_, rel) => `from '${posix.join(MODULE, dir, rel)}'`)

const sdkDir = join(target, 'sdk')
rmSync(sdkDir, { recursive: true, force: true })
mkdirSync(join(sdkDir, 'abi'), { recursive: true })
for (const dir of ['', 'abi']) {
  for (const f of readdirSync(join(pkg, 'src', dir))) {
    if (!f.endsWith('.ts') || f === 'node.ts') continue
    const src = readFileSync(join(pkg, 'src', dir, f), 'utf8')
    writeFileSync(join(sdkDir, dir, f), HEADER + rewrite(src, dir))
  }
}
console.log(`vendored SDK into ${sdkDir}`)

let deployment = {}
if (existsSync(deploymentPath)) {
  deployment = JSON.parse(readFileSync(deploymentPath, 'utf8'))
  console.log(`using ${deploymentPath}`)
} else {
  console.log(`${deploymentPath} not found; writing an empty deployment (hook unset)`)
}
writeFileSync(
  join(target, 'deployment.generated.ts'),
  `// Generated by packages/swap-sdk/scripts/vendor-interface.mjs from deployments/unichain-sepolia.json.\n` +
    `export const PREDICTION_DEPLOYMENT_JSON: Record<string, unknown> = ${JSON.stringify(deployment, null, 2)}\n`,
)
console.log(`wrote ${join(target, 'deployment.generated.ts')}`)

// Match the fork's formatter; generated ABIs may exceed its 500-line lint limit once expanded.
const fork = join(repo, 'interface')
const oxfmt = join(fork, 'node_modules/.bin/oxfmt')
if (existsSync(oxfmt)) {
  execFileSync(oxfmt, [sdkDir, join(target, 'deployment.generated.ts')], { cwd: fork, stdio: 'inherit' })
  for (const dir of ['', 'abi']) {
    for (const f of readdirSync(join(sdkDir, dir)).filter((x) => x.endsWith('.ts'))) {
      const file = join(sdkDir, dir, f)
      const src = readFileSync(file, 'utf8')
      if (src.split('\n').length > 500) writeFileSync(file, `/* oxlint-disable max-lines */\n${src}`)
    }
  }
}
